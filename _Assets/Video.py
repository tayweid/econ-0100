def Make_MOV(video_path, episode_name=None):
    """ Concat mp4 files. """
    media_dir = getattr(config, 'media_dir', 'media')
    if episode_name is None:
        episode_name = media_dir

    video_names = os.listdir(video_path)
    video_names = sorted([x for x in video_names if x.split('.')[-1] == 'mp4'])
    video_paths = ["file '" + video_path + x + "'" for x in video_names]
    text = '\n'.join(video_paths)

    with open('concat.txt', 'w') as f:
        f.write(text)

    output_name = os.path.join(video_path, episode_name + '.mp4')
    os.system('ffmpeg -f concat -safe 0 -i concat.txt -c copy ' + output_name + ' -y')

    os.system('rm concat.txt')
    
    
    """ Convert the mp4 files generated by manim to mov. """
    
    video_names = os.listdir(video_path)
    video_names = [x for x in video_names if '.mp4' in x]

    for video_name in video_names:
        open_path = video_path + video_name
        options = ' -vcodec  mjpeg -q:v 2 -acodec pcm_s16be -q:a 0 -f mov '
        close_path = video_path + video_name.replace('.mp4','_convert.mov')
        
        os.system('ffmpeg -i ' + open_path + options + close_path + ' -y')
        
    """ Copy converted concated file. """
    
    output_name = os.path.join(video_path, episode_name + '.mp4')
    video_name = os.path.join(media_dir, episode_name + '.mp4')
    os.system('cp '+ output_name + ' ' + video_name)
    
    os.system('rm '+output_name)
    os.system('rm '+output_name.replace('.mp4','.mov'))


