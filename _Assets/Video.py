def circle_it(self, radius, point):
    circle_1 = Circle(radius).move_to(point)
    a = Dot(radius = 0.01, color=YELLOW)
    b = TracedPath(a.get_center, dissipating_time=0.3, stroke_opacity=[0, 1]).set_color(YELLOW)
    self.add(a, b)
    self.play(MoveAlongPath(a, circle_1), run_time=1/2)
    self.play(FadeOut(a), FadeOut(b), run_time=1/4)

    
def box_it(self, radius, point):
    framebox = SurroundingRectangle(point, buff = 0.3)
    a = Dot(radius = 0.01, color=YELLOW, z_index=22)
    b = TracedPath(a.get_center, dissipating_time=0.3, stroke_opacity=[0, 1], z_index=22).set_color(YELLOW)
    self.add(a, b)
    self.play(MoveAlongPath(a, framebox), run_time=1/2)
    self.play(FadeOut(a), FadeOut(b), run_time=1/4)
    

def framebox_it(self, item, t=1/2):
    framebox = SurroundingRectangle(item, buff = 0.3, z_index=11).set_color(BLUE)
    self.play(Create(framebox), runtime=t)
    framebox.flip(RIGHT)
    self.play(Uncreate(framebox), runtime=t)


