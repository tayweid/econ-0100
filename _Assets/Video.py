""" Budget Constraint """


def budget_constraint(a, Y, price_a, price_b):
    """ Use the equation for the budget line to return the quantity of b. """
    
    return (Y - price_a * a) / price_b


def move_budget_constraint(axes, Y, price_a, price_b):
    """ Return a plot of the budget line. """
    
    x_max = min(100, Y.get_value()/price_a.get_value())
    return axes.plot(lambda a: budget_constraint(a, Y, price_a, price_b), color=RED, x_range=(0, x_max))


def move_budget_dot(axes, quantity_a, Y, price_a, price_b):
    """ Move a dot along the budget line, with intersection lines. """
    
    x = quantity_a.get_value()
    x_int = axes.coords_to_point(x,0)
    x_label = DecimalNumber(num_decimal_places=2).next_to(x_int,DOWN).set_value(x).set_color(BLUE)
    
    y = budget_constraint(x, Y, price_a, price_b)
    y_int = axes.coords_to_point(0,y)
    y_label = DecimalNumber(num_decimal_places=2).next_to(y_int,LEFT).set_value(y).set_color(GREEN)
    
    p = axes.coords_to_point(x,y)
    dot = Dot(p, z_index=10).set_color(YELLOW)
    
    vline = DashedLine(x_int,p).set_color(GREY)
    hline = DashedLine(y_int,p).set_color(GREY)
    
    return VGroup(dot,vline,hline,x_label,y_label)


""" Indifference Curve """


def utility(quantity_a, quantity_b, tracker=True):
    if tracker:
        return (quantity_a.get_value() * quantity_b.get_value())**(1/2)
    else:
        return (quantity_a * quantity_b)**(1/2)
    

def indifference_curve(U, a, tracker=True):
    if tracker:
        return U.get_value()**2 / a
    else:
        return U**2 / a


def move_indifference_dot(axes, quantity_a, U):
    """ Move a dot along the indifference curve, with intersection lines. """
    
    x = quantity_a.get_value()
    x_int = axes.coords_to_point(x,0)
    x_label = DecimalNumber(num_decimal_places=2).next_to(x_int,DOWN).set_value(x).set_color(BLUE)
    
    y = indifference_curve(U, x)
    y_int = axes.coords_to_point(0,y)
    y_label = DecimalNumber(num_decimal_places=2).next_to(y_int,LEFT).set_value(y).set_color(GREEN)
    
    p = axes.coords_to_point(x,y)
    dot = Dot(p, z_index=10).set_color(YELLOW)
    
    vline = DashedLine(x_int,p).set_color(GREY)
    hline = DashedLine(y_int,p).set_color(GREY)
    
    return VGroup(dot,vline,hline,x_label,y_label)


def move_indifference_curve(axes, U, tracker=True):
    """ Move the MRS line along the indifference curve. """
    
    x_min = min([a for a in np.arange(0, 100, 0.1) if indifference_curve(U, a) < 100])
    
    if tracker:
        return axes.plot(lambda a: indifference_curve(U, a), color=YELLOW, x_range=(x_min, 100, 0.1))
    else:
        return axes.plot(lambda a: indifference_curve(U, a, tracker=False), color=YELLOW, x_range=(x_min, 100, 0.1))
    

def move_indifference_label(axes, U, p):
    label = VGroup(
        Text("U = ").scale(0.8),
        DecimalNumber(num_decimal_places=1).set_value(U.get_value())
    ).set_color(YELLOW)
    
    return label.arrange(RIGHT).next_to(p, RIGHT*2+UP*2)


def mrs_line(quantity_a, U, a):
    """ Use the equation for the MRS line to return the quantity of b. """
    
    quantity_a = quantity_a.get_value()
    derivative = - U.get_value()**2 / quantity_a**2
    quantity_b = indifference_curve(U, quantity_a)
    b_intercept = quantity_b - derivative*quantity_a
    
    return b_intercept + derivative*a


def move_mrs_line(axes, quantity_a, U):
    """ Move the MRS line along the indifference curve. """
    
    return axes.plot(lambda a: mrs_line(quantity_a, U, a), color=PURPLE, x_range=(0, 100, 1), z_index=-10)


""" Consumer Problem """


def solution_a(Y, price_a):
    """ The solution to the consumer's problem for a. """
    
    return Y.get_value() / (2 * price_a.get_value())


def solution_b(Y, price_b):
    """ The solution to the consumer's problem for b. """
    
    return Y.get_value() / (2 * price_b.get_value())


def consumer_solution(axes, Y, price_a, price_b):
    """ Graph the consumer solution. """
    
    a = solution_a(Y, price_a)
    b = solution_b(Y, price_b)
    u = utility(a, b)
    p = axes.coords_to_point(a,b)
    dot = Dot(p, z_index=10).set_color(YELLOW)

    budget = move_budget_constraint(axes, Y, price_a, price_b, tracker=True)
    indifference = move_Indifference_curve(axes, u)
    label = move_Indifference_label(axes, u, p)
    
    return dot, budget, indifference, label


